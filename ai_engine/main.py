# --- Safe startup diagnostics (no secrets) ---
def _log_startup_diagnostics() -> None:
    diag = settings.llm_safe_diagnostics()
    host = diag.get("llm_base_url_host") or "unknown"
    is_prod = os.getenv("NODE_ENV", "").lower() == "production" or os.getenv("ENV", "").lower() == "production"
    localhost_warning = ""
    if diag.get("llm_base_url_is_localhost") and is_prod and not settings.is_local_llm:
        localhost_warning = " [WARNING: base_url points to localhost in production]"
    logger.info(
        "AI_SERVICE_STARTUP llm_configured=%s provider=%s model=%s api_key_present=%s search_configured=%s internal_auth_required=%s%s",
        diag.get("llm_configured"),
        settings.llm_provider,
        diag.get("llm_model") or "none",
        diag.get("llm_api_key_present"),
        settings.search_configured,
        settings.ai_require_internal_token,
        localhost_warning,
    )
    if settings.is_local_llm:
        if settings.llm_configured:
            logger.info(
                "LOCAL_MODEL_STARTUP model=%s ctx=%s threads=%s preload=%s",
                settings.local_model_id,
                settings.local_model_ctx_size,
                settings.local_model_threads,
                settings.local_preload_model,
            )
        else:
            logger.warning(
                "LOCAL_MODEL_CONFIGURATION_INCOMPLETE reason=%s hint=Set LOCAL_MODEL_REPO/LOCAL_MODEL_FILE or LOCAL_MODEL_URL",
                settings.llm_configuration_error,
            )
        return
    if not settings.llm_configured:
        missing: list[str] = []
        if not settings.llm_api_key:
            missing.append("LLM_API_KEY")
        if not settings.llm_model:
            missing.append("LLM_MODEL")
        if not settings.llm_base_url:
            missing.append("LLM_BASE_URL")
        logger.warning(
            "AI_LLM_CONFIGURATION_INCOMPLETE missing=%s llm_key_present=%s llm_model_present=%s llm_base_url_present=%s "
            "hint=Self-hosted default: set LLM_PROVIDER=local (recommended) or legacy LLM_PROVIDER/LLM_API_KEY/LLM_MODEL/LLM_BASE_URL",
            ",".join(missing) if missing else "unknown",
            diag.get("llm_api_key_present"),
            diag.get("llm_model_present"),
            diag.get("llm_base_url_present"),
        )
    else:
        logger.info(
            "AI_PROVIDER_STARTUP_OK provider_host=%s model=%s timeout=%s json_mode=%s",
            host,
            settings.llm_model,
            settings.llm_timeout_seconds,
            settings.llm_json_mode,
        )



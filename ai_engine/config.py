    def local_model_known_entry(self) -> dict[str, object] | None:
        """Verified catalogue metadata for the configured repo/file, if any."""
        if self.local_model_url:
            return None
        return known_model_entry(self.local_model_repo, self.local_model_file)

    @property
    def local_model_expected_sha256(self) -> str:
        """Explicit LOCAL_MODEL_SHA256, else the verified catalogue checksum."""
        pinned = (self.local_model_sha256 or "").strip().lower()
        if pinned:
            return pinned
        entry = self.local_model_known_entry
        return str(entry.get("sha256", "")) if entry else ""

    @property
    def local_model_expected_size(self) -> int:
        """Explicit LOCAL_MODEL_BYTES, else the verified catalogue size."""
        if self.local_model_expected_bytes > 0:
            return self.local_model_expected_bytes
        entry = self.local_model_known_entry
        try:
            return int(entry.get("bytes", 0)) if entry else 0
        except (TypeError, ValueError):
            return 0

    @property
    def local_model_estimated_ram_mb(self) -> int:
        """Rough resident-memory need of the configured model (0 = unknown).

        For the llama.cpp (GGUF) runtime this uses catalogue metadata, then
        scales the KV-cache share for the ACTUAL ``LOCAL_MODEL_CTX``: the
        catalogue figure is quoted at the entry's ``ctx``, and a Render
        instance is sized against what the process will hold at the context it
        really runs. For the PyTorch runtime it estimates from the parameter
        count and the selected dtype (int8 ≈ 1 B/param, bf16 ≈ 2, fp32 ≈ 4)
        plus ~0.9 GB for the torch/transformers runtime, tokenizer, KV cache
        headroom and FastAPI.
        """
        entry = self.local_model_known_entry
        if entry:
            try:
                ram_mb = int(entry.get("ram_mb", 0))
                entry_ctx = int(entry.get("ctx", 0) or 2048)
            except (TypeError, ValueError):
                return 0
            if not ram_mb:
                return 0
            # The catalogue figure is weights + compute buffers + KV cache at
            # ``entry_ctx``. Only the KV part (~36 MiB per 2048 tokens for the
            # small dense families listed above) scales with the window, so a
            # runtime ctx different from the catalogue ctx is adjusted, not
            # blindly trusted.
            kv_at_entry = 36 * max(1, round(entry_ctx / 2048))
            base_mb = max(0, ram_mb - kv_at_entry)
            kv_at_runtime = max(8, int(36 * self.local_model_ctx_size / 2048))
            return base_mb + kv_at_runtime
        if self.local_model_runtime == "torch":
            params = torch_params_for_repo(self.local_model_repo)
            if not params:
                return 0
            dtype = str(self.local_model_dtype or "auto").lower()
            bytes_per_param = 1 if dtype == "int8" else (2 if dtype == "bf16" else 4)
            if dtype == "auto":
                bytes_per_param = 1  # adaptive compute defaults to int8 on CPU
            return int(params * bytes_per_param / (1024 * 1024)) + 900
        expected = self.local_model_expected_size
        # weights + ~35% for KV cache, compute buffers and allocator slack.
        return int(expected / (1024 * 1024) * 1.35) if expected else 0

    @property
    def llm_configured(self) -> bool:
        if self.llm_provider == "local":
            return self.llm_configuration_error is None
        return bool(
            self.llm_provider in {"openai", "openai_compatible"}
            and self.llm_api_key
            and self.llm_model
            and self.llm_base_url
            and self.llm_configuration_error is None
        )

    @property
    def llm_configuration_error(self) -> str | None:
        if self.llm_provider == "local":
            if self.local_model_runtime not in {"torch", "llama_cpp"}:
                return "unsupported_runtime"
            if self.local_model_runtime == "torch":
                # The torch runtime loads a HuggingFace repo id or a local
                # directory that already contains a model (config.json).
                repo = str(self.local_model_repo or "").strip()
                local_dir = Path(repo) if repo else None
                if not repo:
                    return "missing_model_source"
                if self.local_model_url:
                    return "unsupported_for_torch_runtime"  # direct URL is GGUF-only
                if str(self.local_model_file or "").lower().endswith(".gguf"):
                    # A GGUF filename with the torch runtime is a config mistake.
                    return "gguf_file_with_torch_runtime"
                if local_dir and local_dir.exists() and not (local_dir / "config.json").exists():
                    return "local_dir_missing_config"
                return None
            # ---- llama.cpp GGUF runtime (legacy) ----
            if not ((self.local_model_repo and self.local_model_file) or self.local_model_url):
                return "missing_model_source"
            if self.local_model_url:
                try:
                    parsed = urlsplit(self.local_model_url)
                except Exception:
                    return "invalid_model_url"
                host = (parsed.hostname or "").lower()
                if not host or parsed.scheme not in {"http", "https"}:
                    return "invalid_model_url"
                if parsed.scheme == "http" and not _is_private_or_loopback_host(host):
                    return "insecure_model_url"
            elif not str(self.local_model_file).lower().endswith(".gguf"):
                # llama.cpp only loads GGUF; catching this at config time keeps
                # the failure out of the request path.
                return "model_file_not_gguf"
            return None
        if self.llm_provider not in {"openai", "openai_compatible"}:
            return "unsupported_provider"
        try:
            parsed = urlsplit(self.llm_base_url)
            host = (parsed.hostname or "").lower()
        except Exception:
            return "invalid_base_url"
        if not host:
            return "invalid_base_url"
        if parsed.scheme == "http" and not _is_private_or_loopback_host(host):
            # Plain HTTP is only acceptable for self-hosted gateways on a
            # private network; public endpoints must be encrypted.
            return "insecure_base_url"
        if parsed.scheme != "https" and parsed.scheme != "http":
            return "invalid_base_url"
        if self.llm_provider == "openai" and host != "api.openai.com":
            return "provider_base_url_mismatch"
        return None

    @property
    def search_configured(self) -> bool:
        return bool(self.web_search_api_key and self.web_search_provider)


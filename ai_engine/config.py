def _normalize_runtime(raw: str | None) -> str:
    """Map runtime aliases onto {torch, llama_cpp}."""
    value = _clean_env_value(raw).lower()
    if value in {"gguf", "llamacpp", "llama_cpp", "llama.cpp", "llama-cpp", "llamacpp-python"}:
        return "llama_cpp"
    if value in {"pytorch", "transformers", "hf", "torch"}:
        return "torch"
    return value or "llama_cpp"  # unknown values fail validation; never silently choose a runtime


def _normalize_dtype(raw: str | None) -> str:
    value = _clean_env_value(raw).lower()
    normalized = {
        "fp32": "fp32", "float32": "fp32",
        "bf16": "bf16", "bfloat16": "bf16",
        "int8": "int8", "qint8": "int8", "dynamic-int8": "int8",
        "auto": "auto", "": "auto",
    }
    return normalized.get(value, "auto")


def load_settings() -> Settings:
    cors_raw = _clean_env_value(os.getenv("CORS_ORIGIN", ""))
    cors_origins = tuple(
        origin.strip().rstrip("/")
        for origin in cors_raw.split(",")
        if origin.strip()
    ) or (
        "http://localhost:5173",
        "http://127.0.0.1:5173",
        "https://edunova-x.ranjitacharya13.workers.dev",
    )

    # One canonical configuration contract. Provider-specific aliases are intentionally
    # not accepted: aliases made it possible to send a key for one provider to another.
    llm_provider = _first_env("LLM_PROVIDER", default="local").strip().lower()
    if llm_provider in {"gguf", "llama.cpp", "llamacpp", "selfhosted", "self_hosted", "offline"}:
        llm_provider = "local"
    if llm_provider in {"compatible", "custom"}:
        llm_provider = "openai_compatible"
    llm_api_key = _first_env("LLM_API_KEY")
    llm_model = _first_env("LLM_MODEL", default="gpt-4.1-mini")
    llm_model = _clean_env_value(llm_model) or "gpt-4.1-mini"
    raw_base_url = _first_env(
        "LLM_BASE_URL", default="https://api.openai.com/v1"
    )
    llm_base_url = _normalize_base_url(raw_base_url)

    is_local = llm_provider == "local"

    # Runtime + model source selection.  LOCAL_MODEL_RUNTIME explicitly selects
    # the inference runtime; when it is left unset we fall back to llama_cpp for
    # existing GGUF-based deployments (repo ends with -GGUF or a .gguf file is
    # pinned) so a rollout never silently breaks a working model cache, and to
    # torch otherwise.
    runtime_env = _clean_env_value(os.getenv("LOCAL_MODEL_RUNTIME", ""))
    repo_env = _clean_env_value(os.getenv("LOCAL_MODEL_REPO", ""))
    file_env = _clean_env_value(os.getenv("LOCAL_MODEL_FILE", ""))
    is_gguf_deployment = bool(repo_env.upper().endswith("-GGUF")) or file_env.lower().endswith(".gguf")
    local_runtime = _normalize_runtime(runtime_env if runtime_env else ("llama_cpp" if is_gguf_deployment or not repo_env else "torch"))
    local_dtype = _normalize_dtype(os.getenv("LOCAL_MODEL_DTYPE", "auto"))
    torch_compile = _clean_env_value(os.getenv("LOCAL_MODEL_TORCH_COMPILE", "off")).lower()
    if torch_compile not in {"off", "0", "false", "none", "auto", "1", "true", "on"}:
        torch_compile = "off"

    if local_runtime == "llama_cpp":
        default_repo = DEFAULT_LOCAL_MODEL_REPO
        default_file = DEFAULT_LOCAL_MODEL_FILE
    else:
        default_repo = DEFAULT_TORCH_MODEL_REPO
        default_file = ""

    # Provider-aware defaults: the local model runs on a small shared CPU
    # (Render Free: 0.1 core, 512 MiB), so the autonomous loop defaults are
    # tightened to keep single requests fast AND physically inside the window.
    max_iterations = _integer("MAX_AGENT_ITERATIONS", 5 if is_local else 12, 1, 30)
    max_tools = _integer("MAX_TOOL_CALLS", 8 if is_local else 15, 0, 40)
    # For the local model the agent context must physically fit in the llama.cpp
    # window (roughly 3 chars/token) alongside the system prompt and the output
    # budget, otherwise every rich turn hits the truncation guard. At the
    # Render-Free default of ctx 2048 with a 1024-token answer budget, about
    # 1000 prompt tokens (~6k chars) is the largest context the window holds.
    max_context = _integer("AGENT_MAX_CONTEXT_CHARS", 6_000 if is_local else 90_000, 4_000, 250_000)
    max_output = _integer("LLM_MAX_OUTPUT_TOKENS", 1024 if is_local else 3000, 128, 12_000)
    # Production previously pinned 512/900 in the Render dashboard. Do not let
    # that stale optimization silently reintroduce incomplete code or lessons.
    # On the free tier ctx (2048) a 1024-token answer is the largest budget the
    # window can honestly carry alongside the prompt; _fit_to_context protects
    # the rest.
    if is_local:
        max_output = max(1024, max_output)
    local_ctx = _integer("LOCAL_MODEL_CTX", 2048, 1024, 32768)
    if is_local:
        local_ctx = max(2048, local_ctx)
        # No silent context downgrade on small containers: if the configured
        # model + context do not fit, inference/resources.py fails fast with
        # MODEL_RESOURCE_INSUFFICIENT (required/available/recommended MiB)
        # instead of hiding the problem behind a smaller window.

    app_backend_url = _first_env(
        "APP_BACKEND_URL", "EXPRESS_URL", "SERVER_URL", default="http://127.0.0.1:4000"
    ).rstrip("/")

    # ONE thread on llama.cpp instances: Render Free gives ~0.1 CPU and
    # 512 MiB; extra threads add compute-buffer memory and contention without
    # real parallelism on a shared vCPU. Bump LOCAL_MODEL_THREADS on larger
    # instances.
    threads_env = _clean_env_value(os.getenv("LOCAL_MODEL_THREADS", ""))
    threads_default = 0 if local_runtime == "torch" else 1  # 0 = adaptive auto (torch only)
    try:
        threads_value = int(threads_env) if threads_env else threads_default
    except (TypeError, ValueError):
        threads_value = threads_default

    return Settings(
        llm_provider=llm_provider,
        llm_api_key=llm_api_key,
        llm_model=llm_model,
        llm_base_url=llm_base_url,
        llm_timeout_seconds=_integer("LLM_REQUEST_TIMEOUT", 60, 5, 300),
        llm_max_output_tokens=max_output,
        llm_temperature=_floating("LLM_TEMPERATURE", 0.2, 0.0, 1.0),
        llm_json_mode=_boolean("LLM_JSON_MODE", True),
        local_model_runtime=local_runtime,
        local_model_dtype=local_dtype,
        local_model_device=_clean_env_value(os.getenv("LOCAL_MODEL_DEVICE", "auto")).lower() or "auto",
        local_model_hf_revision=_clean_env_value(os.getenv("LOCAL_MODEL_REVISION", "main")) or "main",
        local_model_trust_remote_code=_boolean("LOCAL_MODEL_TRUST_REMOTE_CODE", False),
        local_model_torch_compile=torch_compile,
        local_model_repo=_clean_env_value(os.getenv("LOCAL_MODEL_REPO", default_repo)) or default_repo,
        local_model_file=_clean_env_value(os.getenv("LOCAL_MODEL_FILE", default_file)) or default_file,
        local_model_url=_clean_env_value(os.getenv("LOCAL_MODEL_URL", "")),
        local_model_dir=_clean_env_value(os.getenv("LOCAL_MODEL_DIR", "./models_cache")) or "./models_cache",
        local_model_sha256=_clean_env_value(os.getenv("LOCAL_MODEL_SHA256", "")).lower(),
        local_model_expected_bytes=_integer("LOCAL_MODEL_BYTES", 0, 0, 200_000_000_000),
        local_model_min_bytes=_integer("LOCAL_MODEL_MIN_BYTES", 10 * 1024 * 1024, 4096, 20_000_000_000),
        local_model_download_retries=_integer("LOCAL_MODEL_DOWNLOAD_RETRIES", 3, 0, 8),
        local_model_ctx_size=local_ctx,
        local_model_threads=max(0, min(threads_value, 8)),
        local_model_batch=_integer("LOCAL_MODEL_BATCH", 256, 32, 2048),
        local_model_chat_format=_clean_env_value(os.getenv("LOCAL_MODEL_CHAT_FORMAT", "chatml")).lower() or "chatml",
        local_preload_model=_boolean("LOCAL_PRELOAD_MODEL", True),
        local_chat_wait_seconds=_integer("LOCAL_CHAT_WAIT_TIMEOUT", 120, 1, 300),
        local_model_startup_timeout=_integer("MODEL_STARTUP_TIMEOUT", 300, 10, 900),
        local_inference_idle_timeout=_integer("MODEL_INFERENCE_IDLE_TIMEOUT", 90, 15, 300),
        local_model_download_timeout=_integer("LOCAL_MODEL_DOWNLOAD_TIMEOUT", 1800, 60, 7200),
        # RAG defaults OFF: embedding loading is opt-IN (only for instances with
        # headroom; see Settings.rag_enabled). A 512 MiB inference runtime must
        # never import torch for embeddings just because the variable is unset.
        rag_enabled=_boolean("RAG_ENABLED", False),
        rag_embedding_model=_clean_env_value(os.getenv("RAG_EMBEDDING_MODEL", "")),
        rag_persist_dir=_clean_env_value(os.getenv("RAG_PERSIST_DIR", "")),
        web_search_api_key=_clean_env_value(os.getenv("WEB_SEARCH_API_KEY", "")),
        web_search_provider=_clean_env_value(os.getenv("WEB_SEARCH_PROVIDER", "brave")).lower(),
        web_search_max_results=_integer("WEB_SEARCH_MAX_RESULTS", 5, 1, 10),
        web_request_timeout_seconds=_integer("WEB_REQUEST_TIMEOUT", 10, 2, 30),
        web_max_content_length=_integer("WEB_MAX_CONTENT_LENGTH", 200_000, 10_000, 1_000_000),
        web_max_extracted_chars=_integer("WEB_MAX_EXTRACTED_CHARS", 45_000, 4_000, 100_000),
        web_max_redirects=_integer("WEB_MAX_REDIRECTS", 5, 0, 10),
        max_agent_iterations=max_iterations,
        max_tool_calls=max_tools,
        max_agent_runtime_seconds=_integer("MAX_AGENT_RUNTIME_SECONDS", 180, 30, 900),
        agent_max_context_chars=max_context,
        conversation_max_turns=_integer("CONVERSATION_MAX_TURNS", 12, 2, 30),
        conversation_ttl_seconds=_integer("CONVERSATION_TTL_SECONDS", 86_400, 300, 604_800),
        ai_internal_token=_clean_env_value(os.getenv("AI_INTERNAL_TOKEN", "")),
        ai_require_internal_token=_boolean("AI_REQUIRE_INTERNAL_TOKEN", False),
        app_backend_url=app_backend_url,
        inference_url=_first_env("AI_INFERENCE_URL", "INFERENCE_SERVICE_URL", default="").rstrip("/"),
        inference_request_timeout=_integer("AI_INFERENCE_REQUEST_TIMEOUT", 600, 15, 3600),
        cors_origins=cors_origins,
    )

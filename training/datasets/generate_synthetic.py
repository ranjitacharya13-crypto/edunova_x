def write_splits(out_dir: Path | None = None) -> dict[str, Path]:
    out_dir = out_dir or ROOT
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = all_examples()
    n = len(rows)
    split = max(1, int(n * 0.85))
    train, val = rows[:split], rows[split:]
    paths = {}
    for name, data in (("train.jsonl", train), ("val.jsonl", val), ("all.jsonl", rows)):
        path = out_dir / name
        with path.open("w", encoding="utf-8") as handle:
            for row in data:
                handle.write(json.dumps(row, ensure_ascii=False) + "\n")
        paths[name] = path
    manifest = {
        "name": "edunova-hrm-synthetic-v1",
        "version": "dataset-v1",
        "license": "project-generated; no private student data",
        "source": "training/datasets/generate_synthetic.py",
        "count": n,
        "train": len(train),
        "val": len(val),
        "filtering": "synthetic only; no PII",
        "deduplication": "prompt uniqueness within generator",
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return paths


